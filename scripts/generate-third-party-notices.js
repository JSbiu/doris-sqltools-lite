'use strict';

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const checkOnly = process.argv.includes('--check');
const packages = [
  '@stablelib/aes',
  '@stablelib/binary',
  '@stablelib/blockcipher',
  '@stablelib/cmac',
  '@stablelib/constant-time',
  '@stablelib/ctr',
  '@stablelib/int',
  '@stablelib/siv',
  '@stablelib/wipe',
  'async-limiter',
  'aws-ssl-profiles',
  'browser-or-node',
  'generate-function',
  'hive-driver',
  'iconv-lite',
  'is-property',
  'isomorphic-ws',
  'long',
  'lru.min',
  'mysql2',
  'named-placeholders',
  'node-int64',
  'q',
  'safer-buffer',
  'sql-escaper',
  'thrift',
  'uuid',
  'ws',
];

function readPackage(name) {
  const packageRoot = path.join(projectRoot, 'node_modules', ...name.split('/'));
  const metadata = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'));
  const licenseFile = fs.readdirSync(packageRoot)
    .find((file) => /^(license|licence|copying)(\.|$)/i.test(file));
  if (!licenseFile) throw new Error(`${name}: license file not found`);
  const text = fs.readFileSync(path.join(packageRoot, licenseFile), 'utf8')
    .replace(/\r\n/g, '\n')
    .trim();
  return {
    name,
    version: metadata.version,
    license: typeof metadata.license === 'string' ? metadata.license : 'See bundled text',
    text,
  };
}

const entries = packages.map(readPackage).sort((left, right) => left.name.localeCompare(right.name));
const output = [
  '# Third-Party Notices',
  '',
  'This file is generated by `node scripts/generate-third-party-notices.js`.',
  'It covers the production packages bundled into `dist/extension.js` and shipped in the VSIX.',
  '',
  'The project itself is licensed under MIT. The field encryption implementation also has',
  'specific notices in the repository LICENSE file:',
  '<https://github.com/JSbiu/doris-sqltools-lite/blob/main/LICENSE>',
  '',
  '## Bundled packages',
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...entries.map((entry) => `| \`${entry.name}\` | ${entry.version} | ${entry.license} |`),
  '',
];

for (const entry of entries) {
  output.push(
    `## ${entry.name}@${entry.version}`,
    '',
    `SPDX license: ${entry.license}`,
    '',
    '```text',
    entry.text,
    '```',
    '',
  );
}

const target = path.join(projectRoot, 'THIRD_PARTY_NOTICES.md');
const content = output.join('\n');

if (checkOnly) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current !== content) {
    console.error(
      `${path.relative(projectRoot, target)} is stale; run \`node scripts/generate-third-party-notices.js\`.`,
    );
    process.exitCode = 1;
  } else {
    console.log(`third-party notices current (${entries.length} package notice(s))`);
  }
} else {
  fs.writeFileSync(target, content, 'utf8');
  console.log(`wrote ${path.relative(projectRoot, target)} with ${entries.length} package notice(s)`);
}
